package sysproc

import (
	"os/exec"
	"syscall"
)

// createNoWindow tells CreateProcess not to allocate a console at all.
// This is stronger than STARTF_USESHOWWINDOW with SW_HIDE (HideWindow),
// which still creates the console and only hides it after the fact: the
// window can therefore appear for a frame.
const createNoWindow = 0x08000000

func hideWindow(cmd *exec.Cmd) {
	if cmd.SysProcAttr == nil {
		cmd.SysProcAttr = &syscall.SysProcAttr{}
	}
	cmd.SysProcAttr.CreationFlags |= createNoWindow
}
